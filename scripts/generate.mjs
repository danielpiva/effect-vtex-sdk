import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { correctComponents, correctOperation, checkoutNames } from "./overrides.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(path.join(root, "specs/manifest.json"), "utf8"));
const services = [
  { name: "LegacySearch", file: "Search API", prefix: "", slug: "search-api" },
  { name: "IntelligentSearch", file: "Intelligent Search API - v1", prefix: "/api/intelligent-search/v1", slug: "intelligent-search-api-v1" },
  { name: "IntelligentSearchLegacy", file: "Intelligent Search API", prefix: "/api/io/_v/api/intelligent-search", slug: "intelligent-search-api" },
  { name: "Checkout", file: "Checkout API", prefix: "", slug: "checkout-api" },
  { name: "Payments", file: "Payments Gateway API", prefix: "", slug: "payments-gateway-api" },
];
const pascal = (value) => value.replace(/[^a-zA-Z0-9]+/g, " ").replace(/(?:^|\s)(\w)/g, (_, c) => c.toUpperCase()).replace(/\s/g, "").replace(/^(\d)/, "N$1");
const q = JSON.stringify;
const normalize = (node) => {
  if (!node || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map(normalize);
  return Object.fromEntries(Object.entries(node).filter(([k]) => !["description", "example", "examples", "title", "default", "deprecated", "xml"].includes(k)).map(([k, v]) => [k, normalize(v)]));
};
const catalog = [];
const generated = new Map();
const header = `// Generated from VTEX OpenAPI at ${manifest.commit}.\n// Run npm run generate. Do not edit this file directly.\n`;

for (const service of services) {
  const source = manifest.sources.find((s) => s.file === `VTEX - ${service.file}.json`);
  const bytes = await readFile(path.join(root, "specs", source.file));
  const hash = createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
  if (hash !== source.blob) throw new Error(`Snapshot drift: ${source.file}`);
  const spec = JSON.parse(bytes);
  correctComponents(spec, service.name);
  const resolve = (node) => {
    if (!node?.$ref) return node;
    if (!node.$ref.startsWith("#/")) throw new Error(`Unsupported external reference: ${node.$ref}`);
    const target = node.$ref.slice(2).split("/").reduce((obj, key) => obj?.[key.replace(/~1/g, "/").replace(/~0/g, "~")], spec);
    if (!target) throw new Error(`Missing reference: ${node.$ref}`);
    return { ...target, ...Object.fromEntries(Object.entries(node).filter(([key]) => key !== "$ref")) };
  };
  const definitions = new Map();
  const byShape = new Map();
  const refNames = new Map();
  const nameOf = (node, hint) => {
    node = normalize(node ?? {});
    const shape = JSON.stringify(node);
    if (byShape.has(shape)) return byShape.get(shape);
    let name = pascal(hint) || "Value";
    while (definitions.has(name)) name += "Value";
    byShape.set(shape, name);
    definitions.set(name, node);
    return name;
  };
  const referenced = (ref) => {
    if (refNames.has(ref)) return refNames.get(ref);
    const name = nameOf(resolve({ $ref: ref }), pascal(ref.split("/").at(-1)));
    refNames.set(ref, name);
    return name;
  };
  const render = (node, hint, mode, inline = false) => {
    if (node?.$ref) {
      const base = referenced(node.$ref);
      return node.nullable ? mode === "type" ? `(${base} | null)` : `S.NullOr(${base})` : base;
    }
    node ??= {};
    if (node.nullable) {
      const base = render({ ...node, nullable: false }, hint, mode, inline);
      return mode === "type" ? `(${base} | null)` : `S.NullOr(${base})`;
    }
    if (node.anyOf || node.oneOf || node.allOf) {
      const variants = (node.anyOf ?? node.oneOf ?? node.allOf).map((v, i) => render(v, `${hint}Variant${i + 1}`, mode));
      if (node.allOf) throw new Error("allOf requires a reviewed override");
      return mode === "type" ? `(${variants.join(" | ")})` : `S.Union([${variants.join(", ")}])`;
    }
    if (node.enum) {
      return mode === "type" ? node.enum.map(q).join(" | ") : `S.Literals(${q(node.enum)})`;
    }
    if (node.type === "object" || node.properties || node.additionalProperties) {
      if (!inline) return nameOf(node, hint);
      const entries = Object.entries(node.properties ?? {});
      const required = new Set(node.required ?? []);
      const additional = node.additionalProperties !== false;
      if (mode === "type") {
        return `{\n${entries.map(([key, child]) => `  readonly ${q(key)}${required.has(key) ? "" : "?"}: ${render(child, hint + pascal(key), mode)};`).join("\n")}${additional ? "\n  readonly [key: string]: unknown;" : ""}\n}`;
      }
      const fields = entries.map(([key, child]) => {
        const value = render(child, hint + pascal(key), mode);
        return `  ${q(key)}: ${required.has(key) ? value : `S.optional(${value})`},`;
      });
      const struct = `S.Struct({\n${fields.join("\n")}\n})`;
      return additional ? `S.StructWithRest(${struct}, [S.Record(S.String, S.Unknown)])` : struct;
    }
    if (node.type === "array") {
      const item = render(node.items, hint + "Item", mode);
      if (mode === "type") return `ReadonlyArray<${item}>`;
      return `S.Array(${item})${node.minItems !== undefined ? `.check(S.isMinLength(${node.minItems}))` : ""}${node.maxItems !== undefined ? `.check(S.isMaxLength(${node.maxItems}))` : ""}`;
    }
    const types = { string: ["string", "S.String"], number: ["number", "S.Number"], integer: ["number", "S.Number.check(S.isInt())"], boolean: ["boolean", "S.Boolean"], null: ["null", "S.Null"], void: ["void", "S.Void"] };
    const pair = types[node.type];
    if (!pair) return mode === "type" ? "unknown" : "S.Unknown";
    if (mode === "type") return pair[0];
    let result = pair[1];
    if (node.minimum !== undefined) result += `.check(S.isGreaterThanOrEqualTo(${node.minimum}))`;
    if (node.maximum !== undefined) result += `.check(S.isLessThanOrEqualTo(${node.maximum}))`;
    if (node.minLength !== undefined) result += `.check(S.isMinLength(${node.minLength}))`;
    if (node.maxLength !== undefined) result += `.check(S.isMaxLength(${node.maxLength}))`;
    return result;
  };
  const methods = [];
  for (const [route, item] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
      if (service.name === "Checkout" && route.includes("/pvt/")) continue;
      if (service.name === "Payments" && route !== "/api/payments/transactions/{transactionId}/payments") continue;
      let name;
      if (service.name === "LegacySearch") {
        const cross = { whosawalsosaw: "whoSawAlsoSaw", whosawalsobought: "whoSawAlsoBought", whoboughtalsobought: "whoBoughtAlsoBought", showtogether: "buyTogether", accessories: "accessories", similars: "similars", suggestions: "suggestions" };
        name = route.includes("/crossselling/") ? cross[route.split("/").at(-2)] :
          route === "/api/catalog_system/pub/products/search" ? "search" :
          route.endsWith("/{search}") ? "searchByPath" : route.endsWith("/p") ? "getProductBySlug" :
          route.includes("/offers/") ? route.includes("/sku/") ? "getSkuOffers" : "getProductOffers" :
          route.includes("/facets/category/") ? "getCategoryFacets" : route.includes("/facets/search/") ? "getFacets" : "autocomplete";
      } else if (service.name.startsWith("IntelligentSearch")) {
        const first = route.split("/")[1].replaceAll("_", "-");
        name = { "top-searches": "topSearches", "autocomplete-suggestions": "autocomplete", "search-suggestions": "suggestions", "correction-search": "correction", banners: "banners", "product-search": "search", facets: "facets", products: "getProduct", "pickup-point-availability": "pickupPointAvailability" }[first];
      } else if (service.name === "Payments") name = "sendPayments";
      else name = checkoutNames[operation.operationId] ?? {
        "Delete manual price of an SKU in a cart": "removeManualPrice", "Add item attachment": "addItemAttachment", "Remove item attachment": "removeItemAttachment",
        "Add item subscription attachment": "setSubscriptionData", "Remove item subscription attachment": "removeSubscriptionData", "Attach invoice data": "setInvoiceData",
        "Batch add custom fields": "setCustomFields", "Add order custom field": "setOrderCustomField", "Add item custom field": "setItemCustomField",
        "Remove item custom field": "removeItemCustomField", "Add address custom field": "setAddressCustomField",
      }[operation.summary];
      if (!name) throw new Error(`Name missing: ${service.name} ${method} ${route}`);
      if (methods.some((op) => op.name === name)) throw new Error(`Duplicate operation: ${service.name}.${name}`);
      let input = { type: "object", properties: {}, required: [], additionalProperties: false };
      const parameters = [];
      for (const unresolved of [...(item.parameters ?? []), ...(operation.parameters ?? [])]) {
        const p = resolve(unresolved);
        if (p.in === "header" && ["accept", "content-type", "x-vtex-api-appkey", "x-vtex-api-apptoken"].includes(p.name.toLowerCase())) continue;
        if (!["path", "query", "header"].includes(p.in)) throw new Error(`Unsupported parameter: ${p.in}`);
        input.properties[p.name] = p.schema ?? { type: "string" };
        if (p.required || p.in === "path") input.required.push(p.name);
        parameters.push({ name: p.name, in: p.in, ...(p.style ? { style: p.style } : {}), ...(p.explode !== undefined ? { explode: p.explode } : {}), ...(["facets", "search"].includes(p.name) ? { greedy: true } : {}) });
      }
      const bodySchema = resolve(operation.requestBody)?.content?.["application/json"]?.schema;
      if (bodySchema) {
        input.properties.body = bodySchema;
        if (operation.requestBody.required) input.required.push("body");
      }
      const success = Object.entries(operation.responses ?? {}).filter(([status]) => /^2\d\d$/.test(status));
      let output = success.map(([, response]) => resolve(response)?.content?.["application/json"]?.schema).find(Boolean) ?? { type: "void" };
      ({ input, output } = correctOperation({ service: service.name, path: route, method, operation, input, output, parameters, spec }));
      const inputName = nameOf(input, pascal(name) + "Input");
      const outputName = nameOf(output, pascal(name) + "Output");
      const isCheckout = service.name === "Checkout";
      const kind = service.name === "Payments" ? "payment" : isCheckout && ["placeOrder", "placeOrderFromCart", "processOrder"].includes(name) ? "order" :
        isCheckout && (method !== "get" && name !== "simulate" || ["getOrCreateCart", "clearPersonalData"].includes(name)) ? "cart" : "read";
      const prefix = service.name === "IntelligentSearchLegacy" && route.startsWith("/pickup-point-availability") ? "/api/intelligent-search/v0" : service.prefix;
      const definition = {
        id: service.name + "." + name, method: method.toUpperCase(), path: prefix + route,
        origin: service.name === "Payments" ? "payments" : "store", kind, parameters,
        body: Boolean(bodySchema), emptyResponse: output.type === "void", documentation: `https://developers.vtex.com/docs/api-reference/${service.slug}#${method}-${route.replaceAll("{", "-").replaceAll("}", "-")}`,
      };
      methods.push({ name, inputName, outputName, definition, summary: operation.summary });
      catalog.push({ service: service.name, name, ...definition });
    }
  }
  const rendered = [];
  // Rendering discovers nested/referenced schemas and appends them to this Map.
  for (const [name, schema] of definitions) {
    const type = render(schema, name, "type", true);
    const expression = render(schema, name, "schema", true);
    rendered.push(`export type ${name} = ${type};\nexport const ${name}: S.Codec<${name}> = S.suspend(() => ${expression}) as S.Codec<${name}>;\n`);
  }
  generated.set(`src/generated/${service.name}Models.ts`, header + `import * as S from "effect/Schema";\n\n` + rendered.join("\n"));
  generated.set(`src/generated/${service.name}.ts`, header + `import { makeOperation } from "../Operation.js";\nimport * as M from "./${service.name}Models.js";\nexport * as Models from "./${service.name}Models.js";\n\n` + methods.map(({ name, inputName, outputName, definition, summary }) =>
    `/** ${summary.replaceAll("*/", "")} */\nexport type ${pascal(name)}Input = M.${inputName};\nexport type ${pascal(name)}Output = M.${outputName};\nexport const ${name} = makeOperation({\n  ...${JSON.stringify(definition, null, 2).replaceAll("\n", "\n  ")},\n  input: M.${inputName},\n  output: M.${outputName},\n});\n`).join("\n"));
}
generated.set("src/generated/operations.json", JSON.stringify(catalog, null, 2) + "\n");
generated.set("docs/endpoints.md", `# Endpoint coverage\n\nGenerated from [VTEX OpenAPI](${manifest.repository}/tree/${manifest.commit}) with reviewed corrections. All ${catalog.length} operations below have runtime request/response schemas and typed Effect errors. Access can still require shopper authentication or merchant permissions.\n\n| Module | Function | HTTP | Route | Effect |\n| --- | --- | --- | --- | --- |\n` + catalog.map((op) => `| ${op.service} | ${op.name} | ${op.method} | \`${op.path}\` | ${op.kind} |`).join("\n") + "\n");
let stale = false;
for (const [relative, content] of generated) {
  const file = path.join(root, relative);
  if (check) {
    const current = await readFile(file, "utf8").catch(() => "");
    if (current !== content) { console.error("Stale:", relative); stale = true; }
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
if (stale) process.exitCode = 1;
else console.log(`${check ? "Verified" : "Generated"} ${catalog.length} operations from ${services.length} pinned API schemas.`);
